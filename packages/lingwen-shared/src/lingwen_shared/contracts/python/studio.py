# Projects / active
# ---------------------------------------------------------------------------


class StudioProjectItem(BaseModel):
    """Single project entry returned by ``/studio/projects``."""

    model_config = ConfigDict(extra="ignore")

    slug: str
    name: str
    role: str
    root: str
    location: str


class StudioProjectsResponse(BaseModel):
    """Project listing returned by ``/studio/projects``."""

    model_config = ConfigDict(extra="ignore")

    projects: list[StudioProjectItem]
    active_slug: Optional[str] = None


class StudioActiveResponse(BaseModel):
    """Active project descriptor returned by ``/studio/active``."""

    model_config = ConfigDict(extra="ignore")

    slug: str
    name: str
    root: str
    role: str


class StudioSetActiveRequest(BaseModel):
    """Body for ``PUT /studio/active``."""

    model_config = ConfigDict(extra="ignore")

    slug: str


