    """Prose-diff payload returned by ``/studio/prose-diff``."""

    model_config = ConfigDict(extra="ignore")

    slug: str
    available: bool
    reason: Optional[str] = None
    snapshot_path: Optional[str] = None
    report_path: Optional[str] = None
    save_command: Optional[str] = None
